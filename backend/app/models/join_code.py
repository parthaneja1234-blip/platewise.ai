from sqlalchemy import Column, String, Integer, Boolean, DateTime, ForeignKey
import sqlalchemy as sa
from sqlalchemy.orm import relationship
from app.database import Base
from app.models.base import BaseModelMixin


class MessJoinCode(Base, BaseModelMixin):
    """
    Expiring, limited-use student join codes generated by mess managers.
    Stored hashed (code_hash) for security.
    """
    __tablename__ = "mess_join_codes"

    mess_id = Column(String(36), ForeignKey("cafeterias.id", ondelete="CASCADE"), nullable=False, index=True)
    code_hash = Column(String(64), unique=True, index=True, nullable=False)
    created_by = Column(String(36), ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    max_uses = Column(Integer, default=50, nullable=False, server_default="50")
    used_count = Column(Integer, default=0, nullable=False, server_default="0")
    expires_at = Column(DateTime(timezone=True), nullable=False, index=True)
    is_active = Column(Boolean, default=True, nullable=False, server_default=sa.true())

    # Relationships
    mess = relationship("Cafeteria", backref="join_codes")
    creator = relationship("User", foreign_keys=[created_by])
