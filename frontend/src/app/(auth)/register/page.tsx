"use client";

import React, { useState } from "react";
import Link from "next/link";
import { useAuth } from "@/context/AuthContext";

export default function RegisterStudentPage() {
  const { registerStudent, enterDemoMode } = useAuth();
  const [email, setEmail] = useState("");
  const [fullName, setFullName] = useState("");
  const [password, setPassword] = useState("");
  const [joinCode, setJoinCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);

    if (password.length < 12) {
      setError("Password must be at least 12 characters long.");
      return;
    }

    setLoading(true);
    try {
      await registerStudent({
        email,
        full_name: fullName,
        password,
        join_code: joinCode,
      });
    } catch (err: any) {
      const msg = err?.data?.detail || err?.message || "Registration failed. Please check your join code.";
      setError(typeof msg === "string" ? msg : JSON.stringify(msg));
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="min-h-screen bg-[#0E2412] text-[#FAF8F2] flex flex-col justify-center items-center px-4 py-8 relative overflow-hidden">
      {/* Ambient background glow */}
      <div className="absolute top-[-10%] right-[-10%] w-[500px] h-[500px] rounded-full bg-[#1B4D2E]/40 blur-[120px] pointer-events-none" />
      <div className="absolute bottom-[-10%] left-[-10%] w-[500px] h-[500px] rounded-full bg-[#D4AF37]/20 blur-[140px] pointer-events-none" />

      {/* Main card */}
      <div className="w-full max-w-md bg-[#16381E]/80 backdrop-blur-xl border border-[#2D5A38] rounded-2xl p-8 shadow-2xl z-10">
        {/* Brand header */}
        <div className="text-center mb-6">
          <div className="inline-flex items-center justify-center w-12 h-12 rounded-xl bg-gradient-to-br from-[#2D5A38] to-[#1B4D2E] border border-[#3E7B4C] mb-3 shadow-lg shadow-black/20">
            <span className="text-xl">🎓</span>
          </div>
          <h1 className="text-2xl font-bold tracking-tight text-[#FAF8F2]">
            Student Registration
          </h1>
          <p className="text-xs text-[#A3B899] mt-1">
            Enter the join code provided by your campus dining hall or mess manager
          </p>
        </div>

        {/* Error message */}
        {error && (
          <div className="mb-6 p-4 rounded-xl bg-red-950/60 border border-red-700/60 text-red-200 text-sm flex items-start space-x-3">
            <span className="text-base flex-shrink-0">⚠️</span>
            <div className="leading-snug">{error}</div>
          </div>
        )}

        {/* Registration form */}
        <form onSubmit={handleSubmit} className="space-y-4">
          <div>
            <label
              htmlFor="join-code-input"
              className="block text-xs font-semibold text-[#D4AF37] uppercase tracking-wider mb-1.5"
            >
              Mess Join Code *
            </label>
            <input
              id="join-code-input"
              type="text"
              required
              value={joinCode}
              onChange={(e) => setJoinCode(e.target.value.toUpperCase())}
              placeholder="e.g. PW-7K4M-9281"
              className="w-full px-4 py-3 rounded-xl bg-[#0E2412]/90 border border-[#D4AF37]/60 text-[#FAF8F2] placeholder-[#5A7A60] font-mono tracking-wider focus:outline-none focus:ring-2 focus:ring-[#D4AF37] focus:border-transparent transition-all text-base min-h-[44px]"
            />
            <p className="text-[11px] text-[#A3B899] mt-1">
              Join codes are single-use or limited-capacity codes generated by your mess manager.
            </p>
          </div>

          <div>
            <label
              htmlFor="reg-name-input"
              className="block text-xs font-semibold text-[#A3B899] uppercase tracking-wider mb-1.5"
            >
              Full Name *
            </label>
            <input
              id="reg-name-input"
              type="text"
              required
              value={fullName}
              onChange={(e) => setFullName(e.target.value)}
              placeholder="Aarav Sharma"
              className="w-full px-4 py-3 rounded-xl bg-[#0E2412]/80 border border-[#2D5A38] text-[#FAF8F2] placeholder-[#5A7A60] focus:outline-none focus:ring-2 focus:ring-[#D4AF37] focus:border-transparent transition-all text-base min-h-[44px]"
            />
          </div>

          <div>
            <label
              htmlFor="reg-email-input"
              className="block text-xs font-semibold text-[#A3B899] uppercase tracking-wider mb-1.5"
            >
              Student Email *
            </label>
            <input
              id="reg-email-input"
              type="email"
              required
              value={email}
              onChange={(e) => setEmail(e.target.value)}
              placeholder="student@university.edu"
              className="w-full px-4 py-3 rounded-xl bg-[#0E2412]/80 border border-[#2D5A38] text-[#FAF8F2] placeholder-[#5A7A60] focus:outline-none focus:ring-2 focus:ring-[#D4AF37] focus:border-transparent transition-all text-base min-h-[44px]"
            />
          </div>

          <div>
            <label
              htmlFor="reg-pass-input"
              className="block text-xs font-semibold text-[#A3B899] uppercase tracking-wider mb-1.5"
            >
              Password (Min 12 Characters) *
            </label>
            <input
              id="reg-pass-input"
              type="password"
              required
              minLength={12}
              value={password}
              onChange={(e) => setPassword(e.target.value)}
              placeholder="••••••••••••"
              className="w-full px-4 py-3 rounded-xl bg-[#0E2412]/80 border border-[#2D5A38] text-[#FAF8F2] placeholder-[#5A7A60] focus:outline-none focus:ring-2 focus:ring-[#D4AF37] focus:border-transparent transition-all text-base min-h-[44px]"
            />
          </div>

          <button
            type="submit"
            disabled={loading}
            id="register-submit-btn"
            className="w-full mt-2 py-3.5 px-4 rounded-xl bg-gradient-to-r from-[#D4AF37] to-[#C19B26] hover:from-[#E5BF48] hover:to-[#D4AF37] text-[#0E2412] font-bold text-base shadow-lg shadow-black/20 hover:shadow-black/40 active:scale-[0.99] transition-all disabled:opacity-50 min-h-[44px] flex items-center justify-center cursor-pointer"
          >
            {loading ? (
              <span className="flex items-center space-x-2">
                <span className="w-4 h-4 border-2 border-[#0E2412] border-t-transparent rounded-full animate-spin" />
                <span>Registering…</span>
              </span>
            ) : (
              "Complete Registration"
            )}
          </button>
        </form>

        {/* Existing account link */}
        <div className="mt-5 pt-5 border-t border-[#2D5A38]/50 text-center">
          <p className="text-sm text-[#A3B899]">
            Already registered?{" "}
            <Link
              href="/login"
              id="back-to-login-link"
              className="font-semibold text-[#D4AF37] hover:underline cursor-pointer"
            >
              Sign in here
            </Link>
          </p>
        </div>

        {/* Public Demo fallback */}
        <div className="mt-3 text-center">
          <button
            type="button"
            onClick={enterDemoMode}
            id="register-demo-btn"
            className="w-full py-2.5 px-4 rounded-xl bg-transparent hover:bg-[#1B4D2E]/40 border border-[#2D5A38]/60 text-[#A3B899] hover:text-[#FAF8F2] text-xs font-semibold transition-all min-h-[40px] cursor-pointer"
          >
            ✨ Or explore with synthetic demo data
          </button>
        </div>
      </div>
    </div>
  );
}
